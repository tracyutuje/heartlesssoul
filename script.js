// ======================================
// CREATE UNIQUE BACKGROUNDS
// ======================================

function getBackground(index) {

    const first = 15 + (index * 7) % 35;
    const second = 5 + (index * 11) % 25;

    return `
        radial-gradient(
            circle at ${20 + index * 13 % 70}%
            ${15 + index * 17 % 70}%,
            rgb(${first}, 0, ${second}),
            transparent 65%
        ),
        linear-gradient(
            ${120 + index * 19 % 200}deg,
            #200006,
            #050505,
            #31000c
        )
    `;
}


// ======================================
// DISPLAY QUOTE CARDS
// ======================================

function displayQuotes(category = "All") {

    quoteGrid.innerHTML = "";

    const filteredQuotes = quotes.filter(function(quote) {

        return category === "All" ||
               quote.category === category;

    });

    filteredQuotes.forEach(function(quote) {

        const originalIndex = quotes.indexOf(quote);

        const card = document.createElement("button");

        card.className = "quote-card";

        card.style.background = getBackground(originalIndex);

        card.innerHTML = `
            <span class="card-category">
                ${quote.category}
            </span>

            <p class="card-quote">
                "${quote.text}"
            </p>

            <span class="card-hint">
                CLICK TO EXPAND ↗
            </span>
        `;

        card.addEventListener("click", function() {

            openQuote(quote, originalIndex);

        });

        quoteGrid.appendChild(card);

    });

    quoteCount.textContent =
        `SHOWING ${filteredQuotes.length} OF ${quotes.length} QUOTES`;

}


// ======================================
// CREATE CATEGORY FILTERS
// ======================================

function createFilters() {

    const categories = [
        "All",
        ...new Set(quotes.map(quote => quote.category))
    ];

    categories.forEach(function(category) {

        const button = document.createElement("button");

        button.className = "filter-btn";
        button.textContent = category;

        if (category === "All") {
            button.classList.add("active");
        }

        button.addEventListener("click", function() {

            document.querySelectorAll(".filter-btn")
                .forEach(btn => btn.classList.remove("active"));

            button.classList.add("active");

            displayQuotes(category);

        });

        quoteFilters.appendChild(button);

    });

}


// ======================================
// OPEN FULL SCREEN QUOTE
// ======================================

function openQuote(quote, index) {

    posterText.textContent = `"${quote.text}"`;

    posterCategory.textContent = quote.category;

    quotePoster.style.background = getBackground(index);

    quoteModal.classList.add("show");

    document.body.style.overflow = "hidden";

}


// ======================================
// CLOSE FULL SCREEN QUOTE
// ======================================

function closeQuote() {

    quoteModal.classList.remove("show");

    document.body.style.overflow = "auto";

}

closeModal.addEventListener("click", closeQuote);

quoteModal.addEventListener("click", function(event) {

    if (event.target === quoteModal) {
        closeQuote();
    }

});

document.addEventListener("keydown", function(event) {

    if (event.key === "Escape") {
        closeQuote();
    }

});


// ======================================
// SAVE QUOTE AS IMAGE
// ======================================

saveQuote.addEventListener("click", async function() {

    if (typeof html2canvas === "undefined") {

        alert("Image saving library could not load. Check your internet connection.");

        return;

    }

    saveQuote.textContent = "CREATING IMAGE...";

    try {

        const canvas = await html2canvas(quotePoster, {
            scale: 2,
            backgroundColor: "#050505"
        });

        const link = document.createElement("a");

        link.download = "Heartless-Soul-Quote.png";

        link.href = canvas.toDataURL("image/png");

        link.click();

    } catch (error) {

        alert("Sorry, the image could not be created.");

        console.error(error);

    }

    saveQuote.textContent = "↓ SAVE QUOTE AS IMAGE";

});


